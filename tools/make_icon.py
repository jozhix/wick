#!/usr/bin/env python3
"""Draws Wick's tvOS app icon: an old film-leader countdown frame (rings, crosshair,
big numeral) with grain, scratches and dust. Writes Sources/Assets.xcassets/.

  python tools/make_icon.py            # needs Pillow and numpy
  python tools/make_icon.py preview    # also writes icon-preview.png next to this script

The picture is original artwork generated by this script. Re-run it to change the look
(NUMERAL, SEED, colours below).
"""
import json
import math
import os
import random
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

NUMERAL = "5"
SEED = 7

PAPER = (233, 226, 206)       # off-white film ink
BACK_A = (58, 54, 46)         # background, centre
BACK_B = (22, 20, 17)         # background, edges

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Sources", "Assets.xcassets")
BRAND = os.path.join(ROOT, "App Icon & Top Shelf Image.brandassets")


def find_font(size):
    for name in ("bahnschrift.ttf", "arialbd.ttf", "DejaVuSans-Bold.ttf"):
        for base in ("C:/Windows/Fonts", "/System/Library/Fonts/Supplemental", "/usr/share/fonts/truetype/dejavu"):
            path = os.path.join(base, name)
            if os.path.exists(path):
                return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def grain(w, h, rng, strength):
    n = rng.normal(0.0, strength, (h, w)).astype(np.float32)
    return n


def make_layers(w, h, seed=SEED):
    rng = np.random.default_rng(seed)
    py = random.Random(seed)
    cx, cy = w / 2, h / 2
    r = h * 0.43

    # ---- back: dark warm gradient + vignette + grain + scratches + dust (opaque)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    d = np.sqrt(((xx - cx) / (w * 0.55)) ** 2 + ((yy - cy) / (h * 0.62)) ** 2)
    t = np.clip(d, 0, 1)[..., None]
    a = np.array(BACK_A, np.float32)
    b = np.array(BACK_B, np.float32)
    back = a * (1 - t) + b * t
    back += grain(w, h, rng, 2.6)[..., None]
    # slow flicker bands
    back *= (1.0 + 0.025 * np.sin(yy / h * 9.0 + 0.7))[..., None]
    back_img = Image.fromarray(np.clip(back, 0, 255).astype(np.uint8), "RGB")
    dr = ImageDraw.Draw(back_img, "RGBA")
    for _ in range(max(6, w // 220)):
        x = py.uniform(0, w)
        alpha = py.randint(25, 80)
        wid = max(1, int(w / 1600 * py.choice((1, 1, 2))))
        y0 = py.uniform(0, h * 0.4)
        y1 = y0 + py.uniform(h * 0.3, h)
        dr.line([(x, y0), (x + py.uniform(-6, 6), y1)], fill=(235, 228, 210, alpha), width=wid)
    for _ in range(w // 8):
        x, y = py.uniform(0, w), py.uniform(0, h)
        s = py.uniform(0.6, 2.6) * (w / 1280)
        c = py.choice(((235, 228, 210, 120), (10, 9, 8, 150)))
        dr.ellipse([x - s, y - s, x + s, y + s], fill=c)

    # film strips down both sides: dark band, pale sprocket holes, thin frame line
    strip_w = w * 0.092
    sd2 = ImageDraw.Draw(back_img, "RGBA")
    for x0, x1 in ((0, strip_w), (w - strip_w, w)):
        sd2.rectangle([x0, 0, x1, h], fill=(9, 8, 7, 235))
    hole_w, hole_h = strip_w * 0.34, h * 0.052
    pitch = h * 0.098
    n_holes = int(h / pitch) + 2
    for cxs in (strip_w * 0.5, w - strip_w * 0.5):
        for k in range(n_holes):
            y = k * pitch + pitch * 0.3 + py.uniform(-1.0, 1.0) * (h / 768)
            sd2.rounded_rectangle([cxs - hole_w / 2, y, cxs + hole_w / 2, y + hole_h],
                                  radius=hole_h * 0.28, fill=PAPER + (214,))
    edge = max(2, int(h * 0.006))
    for xe in (strip_w, w - strip_w):
        sd2.line([(xe, 0), (xe, h)], fill=PAPER + (110,), width=edge)

    # ---- middle: rings, crosshair, sweep wedge (transparent)
    mid = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    md = ImageDraw.Draw(mid, "RGBA")
    ink = PAPER + (235,)
    ring = max(3, int(h * 0.018))
    md.ellipse([cx - r, cy - r, cx + r, cy + r], outline=ink, width=ring)
    r2 = r * 0.80
    md.ellipse([cx - r2, cy - r2, cx + r2, cy + r2], outline=PAPER + (200,), width=max(2, ring // 2))
    # crosshair across the whole frame, broken around the numeral
    gap = r * 0.36
    lw = max(2, int(h * 0.008))
    md.line([(strip_w, cy), (cx - gap, cy)], fill=ink, width=lw)
    md.line([(cx + gap, cy), (w - strip_w, cy)], fill=ink, width=lw)
    md.line([(cx, 0), (cx, cy - gap)], fill=ink, width=lw)
    md.line([(cx, cy + gap), (cx, h)], fill=ink, width=lw)
    # tick marks on the outer ring
    for k in range(60):
        ang = math.radians(k * 6)
        L = r * (0.07 if k % 5 == 0 else 0.035)
        x0, y0 = cx + math.cos(ang) * r, cy + math.sin(ang) * r
        x1, y1 = cx + math.cos(ang) * (r - L), cy + math.sin(ang) * (r - L)
        md.line([(x0, y0), (x1, y1)], fill=PAPER + (170,), width=max(1, lw // 2))
    # translucent sweep wedge (the clock-wipe of a leader)
    sweep = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    sd = ImageDraw.Draw(sweep, "RGBA")
    sd.pieslice([cx - r2, cy - r2, cx + r2, cy + r2], start=-90, end=18, fill=PAPER + (46,))
    sd.line([(cx, cy), (cx + math.cos(math.radians(18)) * r2, cy + math.sin(math.radians(18)) * r2)],
            fill=PAPER + (150,), width=lw)
    mid = Image.alpha_composite(mid, sweep)
    # a few dust specks and a scratch on this layer too (reads as parallax)
    for _ in range(w // 30):
        x, y = py.uniform(0, w), py.uniform(0, h)
        s = py.uniform(0.5, 1.8) * (w / 1280)
        md2 = ImageDraw.Draw(mid, "RGBA")
        md2.ellipse([x - s, y - s, x + s, y + s], fill=(240, 232, 214, 150))
    mid = mid.filter(ImageFilter.GaussianBlur(radius=max(0.4, w / 3200)))

    # ---- front: big numeral with a little misregistration (transparent)
    front = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    font = find_font(int(h * 0.62))
    fd = ImageDraw.Draw(front, "RGBA")
    bbox = fd.textbbox((0, 0), NUMERAL, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    tx, ty = cx - tw / 2 - bbox[0], cy - th / 2 - bbox[1]
    off = max(2, int(h * 0.006))
    fd.text((tx + off, ty + off), NUMERAL, font=font, fill=(0, 0, 0, 120))          # soft shadow
    fd.text((tx - off, ty), NUMERAL, font=font, fill=(255, 120, 90, 70))            # warm fringe
    fd.text((tx + off, ty), NUMERAL, font=font, fill=(90, 190, 255, 60))            # cool fringe
    fd.text((tx, ty), NUMERAL, font=font, fill=PAPER + (250,))
    # knock a few scratches through the numeral
    arr = np.array(front)
    for _ in range(max(3, w // 400)):
        x = int(py.uniform(tx, tx + tw))
        arr[:, max(0, x):max(0, x) + max(1, w // 1500), 3] = (arr[:, max(0, x):max(0, x) + max(1, w // 1500), 3] * 0.35).astype(np.uint8)
    front = Image.fromarray(arr, "RGBA").filter(ImageFilter.GaussianBlur(radius=max(0.4, w / 3600)))

    return back_img, mid, front


def flat(w, h):
    back, mid, front = make_layers(w, h)
    img = back.convert("RGBA")
    img = Image.alpha_composite(img, mid)
    img = Image.alpha_composite(img, front)
    return img.convert("RGB")


def write_json(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(obj, f, indent=2)


INFO = {"version": 1, "author": "xcode"}


def save_stack(folder_name, w1, h1):
    """folder_name e.g. 'App Icon - Large'; (w1, h1) is the 1x size."""
    stack = os.path.join(BRAND, folder_name + ".imagestack")
    # render once at 2x, derive 1x
    back, mid, front = make_layers(w1 * 2, h1 * 2)
    layers = [("Front", front, "front"), ("Middle", mid, "middle"), ("Back", back, "back")]
    write_json(os.path.join(stack, "Contents.json"),
               {"layers": [{"filename": n + ".imagestacklayer"} for n, _, _ in layers], "info": INFO})
    for name, img, stem in layers:
        layer = os.path.join(stack, name + ".imagestacklayer")
        write_json(os.path.join(layer, "Contents.json"), {"info": INFO})
        iset = os.path.join(layer, "Content.imageset")
        os.makedirs(iset, exist_ok=True)
        img2x = img
        img1x = img.resize((w1, h1), Image.LANCZOS)
        img1x.save(os.path.join(iset, stem + ".png"), optimize=True)
        img2x.save(os.path.join(iset, stem + "@2x.png"), optimize=True)
        write_json(os.path.join(iset, "Contents.json"), {
            "images": [
                {"idiom": "tv", "filename": stem + ".png", "scale": "1x"},
                {"idiom": "tv", "filename": stem + "@2x.png", "scale": "2x"},
            ],
            "info": INFO,
        })


def save_flat_set(name, w1, h1):
    iset = os.path.join(BRAND, name + ".imageset")
    os.makedirs(iset, exist_ok=True)
    big = flat(w1 * 2, h1 * 2)
    big.save(os.path.join(iset, "image@2x.jpg"), quality=82, optimize=True)
    big.resize((w1, h1), Image.LANCZOS).save(os.path.join(iset, "image.jpg"), quality=82, optimize=True)
    write_json(os.path.join(iset, "Contents.json"), {
        "images": [
            {"idiom": "tv", "filename": "image.jpg", "scale": "1x"},
            {"idiom": "tv", "filename": "image@2x.jpg", "scale": "2x"},
        ],
        "info": INFO,
    })


def main():
    write_json(os.path.join(ROOT, "Contents.json"), {"info": INFO})
    save_stack("App Icon - Large", 1280, 768)
    save_stack("App Icon - Small", 400, 240)
    save_flat_set("Top Shelf Image", 1920, 720)
    save_flat_set("Top Shelf Image Wide", 2320, 720)
    write_json(os.path.join(BRAND, "Contents.json"), {
        "assets": [
            {"size": "1280x768", "idiom": "tv", "filename": "App Icon - Large.imagestack", "role": "primary-app-icon"},
            {"size": "400x240", "idiom": "tv", "filename": "App Icon - Small.imagestack", "role": "primary-app-icon"},
            {"size": "2320x720", "idiom": "tv", "filename": "Top Shelf Image Wide.imageset", "role": "top-shelf-image-wide"},
            {"size": "1920x720", "idiom": "tv", "filename": "Top Shelf Image.imageset", "role": "top-shelf-image"},
        ],
        "info": INFO,
    })
    if len(sys.argv) > 1 and sys.argv[1] == "preview":
        flat(1280, 768).save(os.path.join(os.path.dirname(os.path.abspath(__file__)), "icon-preview.png"))
    print("Wrote", os.path.normpath(BRAND))


if __name__ == "__main__":
    main()
